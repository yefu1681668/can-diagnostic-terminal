/**
  ******************************************************************************
  * @file    cli.h
  * @brief   串口命令行：把诊断仪操作变成可以手敲的命令（演示/调试入口）
  ******************************************************************************
  * USART1 接收中断 -> cli_uart_isr() 填环形缓冲 -> 主循环 cli_poll() 解析执行。
  * 整个诊断流程（会话/解锁/读码/清码/读写 DID）都能在这里一键复现。
  ******************************************************************************
  */
#ifndef __CLI_H
#define __CLI_H

#include <stdint.h>

void cli_init(void);
void cli_poll(void);                /* 主循环调用：解析一行命令并执行 */
void cli_uart_isr(void);            /* USART1 中断里调用：收一个字节进缓冲 */

#endif /* __CLI_H */
